from __future__ import annotations

import argparse
import sys
from pathlib import Path

from parison.cli import parser

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "command-reference.md"


def _formatter(prog: str) -> argparse.HelpFormatter:
    return argparse.HelpFormatter(prog, width=100)


def _walk(current: argparse.ArgumentParser):
    current.formatter_class = _formatter
    yield current
    for action in current._actions:
        if isinstance(action, argparse._SubParsersAction):
            for child in action.choices.values():
                yield from _walk(child)


def render() -> str:
    sections = [
        "# Parison CLI command reference",
        "",
        "This file is generated from the installed command parser. For policy choices, trust boundaries and",
        "end-to-end tasks, use the [current user guide](user-guide.md). Do not edit this file by hand.",
    ]
    root = parser()
    root.prog = "parison"
    for command in _walk(root):
        _, _, stable_help = command.format_help().partition("\n\n")
        sections.extend(("", f"## `{command.prog}`", "", "```text", stable_help.rstrip(), "```"))
    return "\n".join(sections) + "\n"


def main() -> int:
    expected = render()
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; regenerate it", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
